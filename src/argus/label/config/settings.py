# https://stackoverflow.com/questions/4697006/python-split-string-by-list-of-separators
def _split(txt, rems, seps):
    for rem in rems:
        txt = txt.replace(rem, "")
    default_sep = seps[0]
    for sep in seps[1:]:
        txt = txt.replace(sep, default_sep)
    return [i.strip() for i in txt.split(default_sep)]


