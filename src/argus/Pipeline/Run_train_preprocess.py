"""Training pipeline runner for ARGUS preprocessing and model usage.

This module coordinates loading and preprocessing of training data and
provides a minimal entry point for running the training workflow.
"""

import datetime
import logging
from typing import Optional, Tuple

import pandas as pd

from argus.Pipeline.Load_and_preprocess import LoadAndPreprocessor
from argus.utils.config import load_config
from argus.utils.general_functions import get_logs_dir, get_project_root
from argus.utils.logger import Logger


class RunTraining:
    """Run Load and Data preprocessor with ARGUS algorithm."""

    def __init__(self, version="v2_ARGUS25", mode="train", logger=None):
        """Initialize the RunTraining class.

        Args:
            version: Version identifier - default v2_ARGUS25
            mode: "train"
            logger: Optional logger used for pipeline messages.

        """
        self.version = version
        self.mode = mode

        # Create logger if not provided
        if logger is None:
            self.logger = logging.getLogger(__name__)
        else:
            self.logger = logger

        # Load config for gender mappings
        self.config = load_config("general", version=self.version, mode=self.mode)
        self.gender_col = self.config["columns"]["gender"]
        self.gender_map = self.config["mappings"]["gender"]

        # Load models
        self.filename_model_female = self.config["models"]["model_f_filename"]
        self.filename_model_male = self.config["models"]["model_m_filename"]

    def load_and_preprocess(self, run_local=True, load_from_local=False):
        """Load and preprocess the training data for the current run.

        Args:
            run_local: Whether to use local execution for the preprocessing step.
            load_from_local: Whether to load already prepared data from a local source.

        Returns:
            dict: Dictionary containing the processed dataset and any intermediate outputs
                generated by the preprocessing pipeline.

        """
        preprocessor = LoadAndPreprocessor(
            version="v2_ARGUS25",
            mode=self.mode,
            run_local=run_local,
            load_from_local=load_from_local,
            logger=self.logger,
            from_date=self.from_date,
        )

        try:
            results = preprocessor.run_pipeline()
            self.logger.info(f"Processing completed. Final dataset shape: {results['df_merged_all'].shape}")
            return results

        except Exception as e:
            self.logger.error(f"Error in Load and Preprocess script with mode:{self.mode}. Error: {str(e)}")
            raise

    def run(self, from_date: Optional[datetime.datetime] = None) -> Tuple[pd.DataFrame, pd.DataFrame]:
        """Run the training preprocessing pipeline and split the data by gender.

        Args:
            from_date: Optional cutoff date used while loading and preprocessing
                the training data.

        Returns:
            Tuple[pd.DataFrame, pd.DataFrame]: Female and male patient dataframes
                extracted from the merged training dataset.

        """
        self.from_date = from_date

        # TODO - remove run_local and load to set to False
        results = self.load_and_preprocess(run_local=True, load_from_local=False)
        df = results["df_merged_all"]

        code_to_gender = {v: k for k, v in self.gender_map.items()}

        # Find codes for male and female
        female_code = None
        male_code = None

        for code, gender in code_to_gender.items():
            if gender.lower() in ["female"]:
                female_code = code
            elif gender.lower() in ["male"]:
                male_code = code

        if female_code is None or male_code is None:
            self.logger.error(f"Could not find gender code in config: {self.gender_map}")
            raise ValueError("Gender code not found in config")

        df_female = df[df[self.gender_col] == female_code].copy()
        df_male = df[df[self.gender_col] == male_code].copy()

        self.logger.info(f"Split data: {len(df_female)} female, {len(df_male)} male patients")

        return df_female, df_male


if __name__ == "__main__":
    # run script:
    logger = Logger(
        log_file=get_logs_dir() / "RunTraining.log",
        enabled=True,
        df_level=logging.DEBUG,
    )

    data_folder = get_project_root() / "data"

    try:
        # processor = RunInference(mode="inference", logger=logger)
        processor = RunTraining(mode="train", logger=logger)

        df_female, df_male = processor.run()

        # Save preprocessed training data (input for model development)
        df_female.to_parquet(data_folder / "female_argus_data.parquet")
        df_male.to_parquet(data_folder / "male_argus_data.parquet")

        logger.info("Finished running")
        logger.debug(f"df_female looks like: {df_female.head(3)}")
        logger.debug(f"df_male looks like: {df_male.head(3)}")

    except Exception:
        logger.exception("RunTraining crashed")
        raise

    finally:
        df_log = logger.to_dataframe()

    print("Finished run")
